import fs from 'node:fs';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url),source=JSON.parse(fs.readFileSync(new URL('data/verb-question-history.json',root)));
const check=process.argv.includes('--check');
assert.equal(source.schemaVersion,1);
const records=source.records;
assert.deepEqual(records.map(r=>r.entryId),['v:succedere','v:bisognare','v:entrarci','v:cascarci','v:restarci','v:starci','v:uscirne','v:trattarsi']);
for(const r of records){
 assert.equal(r.entry.id,r.entryId);assert.equal(r.previousRevision,'expanded-v1');
 assert(r.currentRevision&&r.currentRevision!==r.previousRevision);
 const ids=r.chapters.flatMap(ch=>ch.groups.flatMap(g=>g.targets.map(t=>t.id)));
 assert.equal(new Set(ids).size,ids.length);
 assert(r.retiredFormTargetIds.length&&new Set(r.retiredFormTargetIds).size===r.retiredFormTargetIds.length&&r.retiredFormTargetIds.every(id=>ids.includes(id)));
 assert(Array.isArray(r.ordinaryChapters)&&r.ordinaryChapters.length===r.chapters.length);
 for(const chapters of [r.chapters,r.ordinaryChapters]){
  assert.equal(new Set(chapters.map(ch=>ch.id)).size,chapters.length);
  assert.equal(new Set(chapters.flatMap(ch=>ch.groups.flatMap(g=>g.targets.map(t=>t.id)))).size,chapters.flatMap(ch=>ch.groups.flatMap(g=>g.targets)).length);
 }
 for(const ch of [...r.chapters,...r.ordinaryChapters])for(const g of ch.groups)for(const t of g.targets){
  assert(t.id.startsWith(r.entryId+'::lesson::'));
  for(const field of ['contexts','legacyAuthoredContexts','legacyExpandedContexts'])if(Object.hasOwn(t,field+'Refs')){
   assert(!Object.hasOwn(t,field));
   assert(Array.isArray(t[field+'Refs'])&&t[field+'Refs'].every(index=>Number.isInteger(index)&&index>=0&&index<r.contextPool.length));
  }
 }
 for(const c of r.contextPool)assert(c.id&&c.it&&c.en&&c.answer&&c.answers?.includes(c.answer)&&Number.isInteger(c.person)&&['ordinary','formal'].includes(c.role||'ordinary'));
}
const output='// Generated by tools/build-verb-question-history.mjs from explicit preserved sources.\nexport const VERB_QUESTION_HISTORY_DATA = '+JSON.stringify(Object.fromEntries(records.map(r=>[r.entryId,r])))+';\n';
const path=new URL('js/learning/verb-question-history-data.js',root);
if(check)assert.equal(fs.readFileSync(path,'utf8'),output,'Preserved question source bundle is stale');
else fs.writeFileSync(path,output);
console.log(records.length+' bounded prior source recipes bundled; no question HTML or executable templates stored.');
