import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { MODEL_IDS, committedHistory, readTrialTurns, messagesFor, percentile, summarize, validateReply, wordErrorRate } from '../dev/phase-1-ai-trial/core.mjs';

assert.equal(MODEL_IDS.length, 3);
assert.deepEqual(wordErrorRate('Non voglio tre biglietti.', 'Voglio due biglietti.'), { referenceWords: 4, edits: 2, rate: .5 });
assert.equal(wordErrorRate('Ho viaggiato in treno.', 'ho viaggiato in treno').rate, 0);
assert.equal(wordErrorRate('', 'silence hallucination').rate, null);
assert.equal(wordErrorRate('è', 'e').rate, 1, 'do not erase meaning-relevant Italian diacritics');
assert.equal(validateReply('<think>hidden</think>Ciao').ok, false, 'never speak internal reasoning markers');
assert.equal(validateReply('').ok, false);
assert.equal(validateReply('Ciao, Carlo. Come stai?').ok, true);
assert.equal(messagesFor('test', 'B2', Array.from({ length: 20 }, (_, i) => ({ role: 'user', content: String(i) }))).length, 8, 'bounded history');
assert.deepEqual(committedHistory([{ role: 'user', content: 'saved', status: 'committed' }, { role: 'assistant', content: 'draft', status: 'draft' }]), [{ role: 'user', content: 'saved' }]);
assert.equal(committedHistory(Array.from({ length: 12 }, (_, i) => ({ role: 'user', content: String(i), status: 'committed' }))).length, 6);
assert.deepEqual(readTrialTurns({ getItem: () => '{broken' }, 'trial').turns, []);
assert.match(readTrialTurns({ getItem: () => { throw Error('Storage blocked'); } }, 'trial').error, /Storage blocked/);
assert.deepEqual(readTrialTurns({ getItem: () => 'null' }, 'trial').turns, []);
assert.equal(percentile([8, 1, 5, 3, 2], .95), 8);
const summary = summarize([{ mode: 'written', ok: true, llmMs: 300 }, { mode: 'manual', ok: false }, { mode: 'handsfree', ok: true, llmMs: 400, endToFirstAudioMs: null }]);
assert.equal(summary.written.llmP50Ms, 300);
assert.equal(summary.manual.failures, 1);
assert.equal(summary.handsfree.endToFirstAudioP50Ms, null, 'fixture processing is not a live end-of-speech measurement');
const root = new URL('../dev/phase-1-ai-trial/', import.meta.url);
const [app, asr, llm, prepare, production] = await Promise.all(['app.mjs', 'asr-worker.mjs', 'llm-worker.mjs', 'prepare.mjs'].map(file => readFile(new URL(file, root), 'utf8')).concat(readFile(new URL('../js/learning/assistant.js', import.meta.url), 'utf8')));
assert.match(asr, /allowRemoteModels = false/);
assert.match(asr, /allowLocalModels = true/);
assert.match(asr, /language: 'italian'/);
assert.match(llm, /CreateMLCEngine/);
assert.match(app, /v\.localService === true/);
assert.match(app, /manualDraft = null/);
assert.match(app, /token !== epoch/);
assert.match(app, /if \(busy\) throw Error/);
assert.match(app, /Stale synthesis cancelled before playback/);
assert.match(app, /options\.history === undefined \? committedHistory\(turns\)/);
assert.match(app, /level: c\.level, history: \[\]/, 'isolated quality cases must not inherit conversation history');
assert.match(prepare, /pins\.repositories\[repo\]/);
assert.doesNotMatch(production, /phase-1-ai-trial/, 'disposable trial must not be a production boot dependency');
const pins = JSON.parse(await readFile(new URL('pins.json', root)));
assert.match(pins.binaryRevision, /^[a-f0-9]{40}$/);
for (const sha of Object.values(pins.repositories)) assert.match(sha, /^[a-f0-9]{40}$/);
console.log('AI trial safeguards passed: distinct modes, source-labelled timings, Italian error preservation, bounded prompt, pinned/local-only runtime and production isolation.');
