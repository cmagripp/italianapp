import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {buildLesson} from '../js/learning/lesson-content.js';
import {buildJourneyQuestion} from '../js/learning/lesson-questions.js';
const root=new URL('../',import.meta.url),verbs=JSON.parse(fs.readFileSync(new URL('data/verbs.json',root)));
const baseline=JSON.parse(execFileSync('git',['show','7eeeb36:data/verbs.json'],{cwd:root,encoding:'utf8'}));
const old=baseline.find(e=>e.inf==='baciare'),current=verbs.find(e=>e.inf==='baciare');
const requirements=p=>p.chapters.filter(c=>!c.optional).map(c=>({id:c.id,targets:c.groups.flatMap(g=>g.targets).filter(t=>t.required!==false&&t.available!==false).map(t=>t.id)}));
assert.deepEqual(requirements(buildLesson(current,{legacy:true})),requirements(buildLesson(old,{legacy:true})));
assert.deepEqual(buildLesson(current).chapters.map(c=>c.legacyRequirements),buildLesson(old).chapters.map(c=>c.legacyRequirements));
assert.equal(current.examples[0].it,'Bacia tua figlia sulla guancia.');
assert(!current.usage.includes('In Italy friends greet'));
const d=verbs.find(e=>e.inf==='domandare'),plan=buildLesson(d),chapter=plan.chapters.find(c=>c.id==='present');
const target=chapter.groups.flatMap(g=>g.targets).find(t=>t.id.endsWith('::form-0'));
const legacy=target.legacyAuthoredContexts.find(s=>s.it.includes('una domanda'));
assert(legacy,'Old raw frame remains available to a baseline cursor');
const saved=buildJourneyQuestion(d,chapter,target,{variant:target.legacyAuthoredContexts.indexOf(legacy),format:'type',phase:'independent'});
assert.equal(saved.context.it,'Io domando una domanda.');assert.equal(saved.context.en,'I ask a question.');assert.deepEqual(saved.answer,['domando']);
const freshIndex=target.contexts.findIndex(s=>s.it==='Io domando a Sara come sta.');assert(freshIndex>=0);
const fresh=buildJourneyQuestion(d,chapter,target,{variant:freshIndex,format:'type',phase:'independent',scenePolicy:'expanded-v1'});
assert.equal(fresh.context.it,'Io domando a Sara come sta.');assert.equal(fresh.context.en,'I ask Sara how she is.');assert.deepEqual(fresh.answer,saved.answer);
console.log('Baciare baseline required target sets and teaching-only example preserved; domandare original raw cursor and corrected fresh frame verified. Saved expanded-v1 cursors require the separately tested revision fence.');
